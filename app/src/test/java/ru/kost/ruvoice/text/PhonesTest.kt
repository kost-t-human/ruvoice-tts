package ru.kost.ruvoice.text

import org.junit.Assert.assertEquals
import org.junit.Test

/** Телефоны СНГ во всех ходовых записях (TalkBack читает ими звонки, СМС, контакты). */
class PhonesTest {
    private fun n(s: String) = Normalizer.numbers(s)
    private fun off(vararg k: String) = Rules(off = k.toSet())

    private val ru = "плюс семь, девятьсот, ноль восемьдесят три, ноль девять, девяносто три"
    private val ru8 = "восемь, девятьсот, ноль восемьдесят три, ноль девять, девяносто три"

    @Test fun russiaAllWritings() {
        for (s in listOf("+7 900 083 09 93", "+7 (900) 083-09-93", "+7(900)083-09-93", "+7 (900) 083-0993",
            "+7-900-083-09-93", "+7 900 0830993", "+7 900 083 0993", "+79000830993", "+7 900 083 09 93"))
            assertEquals(s, ru, n(s))
        for (s in listOf("8 (900) 083-09-93", "8(900)0830993", "8-900-083-09-93", "8 900 083 09 93",
            "8 900 083-0993", "89000830993"))
            assertEquals(s, ru8, n(s))
        assertEquals("семь, девятьсот, ноль восемьдесят три, ноль девять, девяносто три", n("7 900 083 09 93"))
        assertEquals("девятьсот, ноль восемьдесят три, ноль девять, девяносто три", n("(900) 083-09-93"))
        assertEquals("девятьсот, ноль восемьдесят три, ноль девять, девяносто три", n("900 083 09 93"))
        assertEquals("девятьсот, ноль восемьдесят три, ноль девять, девяносто три", n("900-083-09-93"))
        assertEquals("восемь, восемьсот, пятьсот пятьдесят пять, тридцать пять, тридцать пять", n("8 800 555-35-35"))
    }

    @Test fun cityCodes() {
        assertEquals("плюс семь, четыреста девяносто пять, сто двадцать три, сорок пять, шестьдесят семь", n("+7 (495) 123-45-67"))
        assertEquals("четыреста девяносто пять, сто двадцать три, сорок пять, шестьдесят семь", n("(495) 123-45-67"))
        assertEquals("плюс семь, сорок девять, пятьдесят два, двенадцать, тридцать четыре, пятьдесят шесть", n("+7 (4952) 12-34-56"))
        assertEquals("восемь, семьсот один, сто двадцать три, сорок пять, шестьдесят семь", n("8 701 123 45 67"))
    }

    @Test fun localNumbers() {
        assertEquals("сто двадцать три, сорок пять, шестьдесят семь", n("123-45-67"))
        assertEquals("двенадцать, тридцать четыре, пятьдесят шесть", n("12-34-56"))
        assertEquals("один, двадцать три, сорок пять", n("1-23-45"))
    }

    @Test fun cis() {
        val ua = "плюс триста восемьдесят, сорок четыре, сто двадцать три, сорок пять, шестьдесят семь"
        for (s in listOf("+380 44 123 45 67", "+380 (44) 123-45-67", "+380441234567")) assertEquals(s, ua, n(s))
        assertEquals("ноль сорок четыре, сто двадцать три, сорок пять, шестьдесят семь", n("044 123 45 67"))
        assertEquals("ноль сорок четыре, сто двадцать три, сорок пять, шестьдесят семь", n("(044) 123-45-67"))
        assertEquals("ноль шестьдесят семь, сто двадцать три, сорок пять, шестьдесят семь", n("067-123-45-67"))
        assertEquals("плюс тридцать восемь, ноль сорок четыре, сто двадцать три, сорок пять, шестьдесят семь", n("+38 044 123 45 67"))

        val by = "плюс триста семьдесят пять, двадцать девять, сто двадцать три, сорок пять, шестьдесят семь"
        for (s in listOf("+375 29 123-45-67", "+375 (29) 123-45-67", "+375291234567")) assertEquals(s, by, n(s))
        val by8 = "восемь, ноль двадцать девять, сто двадцать три, сорок пять, шестьдесят семь"
        for (s in listOf("8 029 123-45-67", "8 (029) 123-45-67", "80291234567")) assertEquals(s, by8, n(s))

        val uz = "плюс девятьсот девяносто восемь, девяносто, сто двадцать три, сорок пять, шестьдесят семь"
        for (s in listOf("+998 90 123-45-67", "+998901234567")) assertEquals(s, uz, n(s))
        assertEquals("плюс девятьсот девяносто шесть, пятьсот пятьдесят пять, сто двадцать три, четыреста пятьдесят шесть", n("+996 555 123 456"))
        assertEquals("плюс девятьсот девяносто шесть, пятьсот пятьдесят пять, двенадцать, тридцать четыре, пятьдесят шесть", n("+996555123456"))
        assertEquals("плюс девятьсот девяносто два, девяносто три, сто двадцать три, сорок пять, шестьдесят семь", n("+992 93 123 4567"))
        assertEquals("плюс триста семьдесят четыре, девяносто один, двенадцать, тридцать четыре, пятьдесят шесть", n("+374 (91) 12-34-56"))
        assertEquals("плюс триста семьдесят четыре, девяносто один, двенадцать, тридцать четыре, пятьдесят шесть", n("+374 91123456"))
        assertEquals("плюс девятьсот девяносто четыре, пятьдесят, сто двадцать три, сорок пять, шестьдесят семь", n("+994 50 123 45 67"))
        assertEquals("плюс девятьсот девяносто пять, пятьсот пятьдесят пять, двенадцать, тридцать четыре, пятьдесят шесть", n("+995555123456"))
        assertEquals("плюс триста семьдесят три, двадцать два, сто двадцать три, четыреста пятьдесят шесть", n("+373 22 123 456"))
        assertEquals("плюс девятьсот девяносто три, двенадцать, тридцать четыре, пятьдесят шесть, семьдесят восемь", n("+993 12 34-56-78"))
        assertEquals("плюс один, двести двенадцать, пятьсот пятьдесят пять, двенадцать, тридцать четыре", n("+1 212 555 1234"))
    }

    @Test fun inText() {
        assertEquals("Звоните: $ru, добавочный сто двадцать три.",
            Normalizer.numbers("Звоните: +7 (900) 083-09-93, доб. 123."))
        assertEquals("телефон $ru8 или восемь, восемьсот, пятьсот пятьдесят пять, тридцать пять, тридцать пять",
            n("тел. 8 900 083 09 93 или 8 800 555 35 35"))
        assertEquals("Позвони на $ru8!", n("Позвони на 89000830993!"))
        assertEquals("$ru два раза", n("+7 900 083 09 93 2 раза"))
    }

    @Test fun notPhones() {
        assertEquals("один миллион двести тысяч", n("1 200 000"))
        assertEquals("два миллиона пятьсот тысяч рублей", n("2 500 000 рублей"))
        assertEquals("двенадцатого мая две тысячи двадцать четвёртого года", n("12.05.2024"))
        assertEquals("десять-двадцать", n("10-20"))
        assertEquals("восемьдесят миллиардов", n("80000000000"))
        assertEquals("ИНН семь миллиардов семьсот семь миллионов восемьдесят три тысячи восемьсот девяносто три", n("ИНН 7707083893"))
        assertEquals(n("СНИЛС 123-456-789 01"), Normalizer.numbers("СНИЛС 123-456-789 01", off("phones")))
        assertEquals(n("ISBN 978-5-17-118366-0"), Normalizer.numbers("ISBN 978-5-17-118366-0", off("phones")))
        assertEquals(n("+5 000 000 000"), Normalizer.numbers("+5 000 000 000", off("phones")))
    }

    @Test fun ruleOff() {
        assertEquals("+семь тысяч девятьсот восемьдесят три девять девяносто три",
            Normalizer.numbers("+7 900 083 09 93", off("phones")))
    }
}
