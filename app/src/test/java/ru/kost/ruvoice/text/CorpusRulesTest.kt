package ru.kost.ruvoice.text

import org.junit.Assert.assertEquals
import org.junit.Test

/** Правила, добавленные по корпусу ru-normalizr (см. RuNormalizrCorpusTest). Ядро без latin(). */
class CorpusRulesTest {
    private fun n(s: String) = Abbrev.apply(Normalizer.numbers(Normalizer.punctuation(s)))

    @Test fun ordinalSuffixesWithoutHyphen() {
        assertEquals("пятая группа", n("5я группа"))
        assertEquals("третьего номера", n("3го номера"))
        assertEquals("в двадцать первом году", n("в 21ом году"))
        assertEquals("в сорок первом году", n("в 41м году"))
        assertEquals("первую секунду", n("1-ую секунду"))
        assertEquals("Пётр первый", n("Пётр 1-ый"))
        assertEquals("шесть метров", n("6м"))
        assertEquals("пятый этаж", n("5 - й этаж"))
    }

    @Test fun decadesAndRoundHundreds() {
        assertEquals("тысяча девятьсот шестидесятые годы", n("1960-е гг."))
        assertEquals("в лихие девяностые.", n("в лихие 90-е."))
        assertEquals("первое", n("1-е"))
        assertEquals("в шестидесятых годах", n("в 60-х гг."))
        assertEquals("в тысяча девятисотом году", n("в 1900 году"))
        assertEquals("около пятисотого года до нашей эры", n("около 500 года до н. э."))
    }

    @Test fun decimalsAndPercent() {
        assertEquals("ноль целых три миллиардных", n("0,000000003"))
        assertEquals("двадцать процентов личного", n("20 % личного"))
        assertEquals("двенадцать целых пять десятых процента", n("12,5%"))
        assertEquals("девяносто процентов всей", n("90 % процентов всей"))
        assertEquals("две целых пять десятых миллиона человек", n("2,5 млн человек"))
    }

    @Test fun units() {
        assertEquals("пять мегабайтов", n("5 МБ"))
        assertEquals("пять мегабит", n("5 Mb"))
        assertEquals("ток пять миллиампер", n("ток 5 мА"))
        assertEquals("двенадцать кадров в секунду", n("12 fps"))
        assertEquals("два квадратных километра", n("2 км2"))
        assertEquals("три кубических метра", n("3 м^3"))
        assertEquals("девяносто километров в час", n("90 км/ч"))
        assertEquals("пять миллиграммов на килограмм", n("5 мг/кг"))
        assertEquals("тридцать пять миллиметров", n("35-мм"))
        assertEquals("одни сутки, двое суток, пять суток.", n("1 сут., 2 сут., 5 сут."))
        assertEquals("пять лир", n("5 ₺"))
        assertEquals("до тридцати – сорока сантиметров", n("до 30 – 40 см"))
        assertEquals("от шестидесяти до восьмидесяти тысяч", n("от 60 до 80 тыс."))
    }

    @Test fun compoundsAndArithmetic() {
        assertEquals("пятитонный груз", n("5-тонный груз"))
        assertEquals("двухместный", n("2х местный"))
        assertEquals("однокомнатная", n("1-комнатная"))
        assertEquals("три комнатных растения", n("3 комнатных растения"))
        assertEquals("тысячелетний", n("1000-летний"))
        assertEquals("нулепроцентный", n("0-процентный"))
        assertEquals("два умножить на три равно шесть", n("2×3=6"))
        assertEquals("десять минус пять равно пять", n("10-5 = 5"))
        assertEquals("пять минус два", n("5−2"))
        assertEquals("x = y", n("x = y"))
        assertEquals("два в степени три", n("2^3"))
    }

    @Test fun chaptersAndRoman() {
        assertEquals("Глава десятая. Конец.", n("Глава 10. Конец."))
        assertEquals("в главе десятой", n("в главе 10"))
        assertEquals("смотри главу пятую и рисунок три.", n("См. гл. 5 и рис. 3."))
        assertEquals("глава двенадцатая, страница три", n("глава 12, страница 3"))
        assertEquals("В пятнадцатом веке", n("В XV в."))
        assertEquals("К четвёртому кварталу", n("К IV кв."))
        assertEquals("Моряки пятнадцатого и шестнадцатого веков", n("Моряки XV и XVI веков"))
        assertEquals("С шестнадцатого по восемнадцатый век", n("С XVI по XVIII вв."))
        assertEquals("Между пятнадцатым и шестнадцатым веками", n("Между XV и XVI веками"))
        assertEquals("Армия Людовика шестнадцатого", n("Армия Людовика XVI"))
        assertEquals("К Георгу шестому", n("К Георгу VI"))
        assertEquals("Екатерина вторая", n("Екатерина II"))
        assertEquals("Дональда седьмого", n("Дональда VII-го"))
        assertEquals("В главах четвёртой и пятой", n("В главах IV и V"))
    }

    @Test fun datesYearsAndCases() {
        assertEquals("пятнадцатого марта две тысячи двадцать первого года.", n("15.03.2021 г."))
        assertEquals("пятнадцатого марта две тысячи двадцать первого года. Потом", n("15.03.2021 г. Потом"))
        assertEquals("перед восьмым марта", n("перед 8 марта"))
        assertEquals("iOS восемнадцать целых четыре десятых", n("iOS 18.4"))
        assertEquals("пятьдесят пятого года рождения", n("55 г.р."))
        assertEquals("около пятидесятого года нашей эры", n("около 50 н. э."))
        assertEquals("с две тысячи двадцатого по две тысячи двадцать четвёртый год", n("с 2020 по 2024 год"))
        assertEquals("в тысяча девятьсот сорок третьем и тысяча девятьсот пятьдесят первом годах", n("в 1943 и 1951 гг."))
        assertEquals("вес сто двадцать три грамма.", n("вес 123 г."))
        assertEquals("Выдали по одному рублю", n("Выдали по 1 рублю"))
        assertEquals("Доступ четырём сотрудникам", n("Доступ 4 сотрудникам"))
        assertEquals("больше чем двумя людьми", n("больше чем 2 людьми"))
        assertEquals("Соотношение три к одному.", n("Соотношение 3 к 1."))
        assertEquals("более-менее пять минут", n("более-менее 5 минут"))
        assertEquals("завод имени Ленина", n("завод им. Ленина"))
        assertEquals("деньги им. Они откроют", n("деньги им. Они откроют"))
        assertEquals("Фр+идрих +Август", n("Фри́дрих А́вгуст"))
        // ссылка по частям, схема не читается; drop_links выкидывает её целиком
        assertEquals("Откройте эй точка би слэш пять mb слэш эс и", n("Откройте https://a.b/5Mb/s и"))
        assertEquals("смотри www точка ya точка ru слэш page вопрос id равно четыре два амперсанд экс равно один, дальше",
            n("см. www.ya.ru/page?id=42&x=1, дальше"))
        assertEquals("Откройте и.", Normalizer.numbers("Откройте https://a.b/5Mb/s и.", Rules(setOf("drop_links"))))
        assertEquals("Ryzen пять тысяч восемьсот экс три ди, джи пи т+и-четыре оу, экран одна тысяча восемьдесят пи, витамин-ди",
            n("Ryzen 5800X3D, GPT-4o, экран 1080p, витамин-D"))
        assertEquals("пиши на mail точка ru собака example точка com, не на тот", n("пиши на mail.ru@example.com, не на тот"))
        assertEquals("Откройте https://a.b/5Mb/s и пять штук", Normalizer.numbers("Откройте https://a.b/5Mb/s и 5 штук", Rules(setOf("read_links"))))
        assertEquals("два + три = пять", Normalizer.numbers("2 + 3 = 5", Rules(setOf("arith"))))
        assertEquals("пиши на www точка ya точка ru, не на",
            Normalizer.numbers("пиши на a@b.ru www.ya.ru, не на", Rules(setOf("drop_emails"))))
        assertEquals("версия два точка ноль три точка один", n("версия 2.03.1"))
        assertEquals("GPT четыре точка пять", n("GPT-4.5").replace("джи пи т+и-", "GPT "))
    }

    // Род/число по окончанию соседнего слова, диапазоны лет, список римских (корпус ru-normalizr, вторая порция).
    @Test fun agreementByEnding() {
        assertEquals("одна женщина, двадцать одна минута, одно новое сообщение, один новый друг, на один больше, один тенге",
            n("1 женщина, 21 минута, 1 новое сообщение, 1 новый друг, на 1 больше, 1 тенге"))
        assertEquals("более одного года, ни одного раза, по поводу пяти вопросов", n("более 1 года, ни 1 раза, по поводу 5 вопросов"))
        assertEquals("вторые ножницы, второе место, пятые классы, шестое июля", n("2-е ножницы, 2-е место, 5-е классы, 6-е июля"))
        assertEquals("в третьей дивизии, первый номер, с третьей попытки, на первой полосе, третий день",
            n("в 3-й дивизии, 1-й номер, с 3-й попытки, на 1-й полосе, 3-й день"))
        assertEquals("Главы четвёртая, пятая и шестая переработаны", n("Главы IV, V и VI переработаны"))
        assertEquals("в сорок четвёртом – сорок пятом годах и сорок четвёртый – сорок пятый годы",
            n("в 44-45 гг. и 44-45 гг."))
        assertEquals("В трёхсотом – двухсотом годах до нашей эры и (двенадцать тысяч пятисотый – девять тысяч пятисотый годы до нашей эры)",
            n("В 300-200 г. до н. э. и (12500-9500 до н. э.)"))
        assertEquals("один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь, сто девяносто два точка сто шестьдесят восемь точка сто точка двести",
            n("1.234.567, 192.168.100.200"))
        assertEquals("В восемь часов утром, строили два века подряд", n("В 8.00 утром, строили 2 в. подряд"))
        assertEquals("два миллилитра в минуту, четыре киловатт-часа, пять килограммов / шт", n("2 мл / мин, 4 кВт · ч, 5 кг / шт"))
    }

    // Род на «-ь» (SoftSignGender), женское имя перед «N-й», управление глагола, «одну тысячу».
    @Test fun softSignNamesAndVerbs() {
        assertEquals("одна пасть, одна ночь, одна цель, один гость, один путь, одна модель, один рубль, одна новость",
            n("1 пасть, 1 ночь, 1 цель, 1 гость, 1 путь, 1 модель, 1 рубль, 1 новость"))
        assertEquals("Елизаветы третьей, Марии первой, Людовика четырнадцатый", n("Елизаветы 3-й, Марии 1-й, Людовика 14-й"))
        assertEquals("достигаем пяти целей, требует пяти минут, не хватает трёх рублей, касса пять рублей, лишние пять минут",
            n("достигаем 5 целей, требует 5 минут, не хватает 3 рублей, касса 5 рублей, лишние 5 минут"))
        assertEquals("иметь одну тысячу долларов, за одну тысячу долларов, стоит двадцать одну тысячу рублей, по одной тысяче рублей, за две тысячи лет",
            n("иметь 1000 долл., за 1000 долл., стоит 21000 рублей, по 1000 рублей, за 2000 лет"))
    }

    // Третья порция: винительный женской единицы, потерянный разделитель в единице, дробь после
    // триггера, «смотри»-перечисление, неправильная дробь, год в скобках, «Св.», «от лат.».
    @Test fun unitsFractionsAndSaints() {
        assertEquals("стоит одну лиру, на одну миллисекунду, в одну минуту, пять минут", n("стоит 1 ₺, на 1 мс, в 1 мин, 5 мин"))
        assertEquals("девяносто километров в час и пять киловатт-часов, двенадцать оборотов в минуту, три метра с ветром",
            n("90 км ч и 5 квт ч, 12 об мин, 3 м с ветром"))
        assertEquals("от минус пяти целых двух десятых до трёх, около пяти, от одной целой одной десятой до двух",
            n("от -5.2 до 3, около 5, от 1,1 до 2"))
        assertEquals("при минус двадцати градусах Цельсия, до пяти градусов, к десяти градусам", n("при -20°C, до 5°, к 10°"))
        assertEquals("от потери ста долларов, потерял пять рублей", n("от потери 100 долларов, потерял 5 рублей"))
        assertEquals("смотри рисунок два и таблицу три, страницу четыре. На странице шесть таблица семь.",
            n("см. рис. 2 и табл. 3, стр. 4. На стр. 6 табл. 7."))
        assertEquals("семь вторых, сто сотых, двадцать четыре дробь семь, двадцать пять дробь три", n("7/2, 100/100, 24/7, 25/3"))
        assertEquals("Аустерлицем (тысяча восемьсот пятый). Джокер (две тысячи девятнадцатый)", n("Аустерлицем (1805). Джокер (2019)"))
        assertEquals("с двенадцать тысяч пятисотого по девять тысяч пятисотый год до нашей эры", n("с 12500 по 9500 до н. э."))
        assertEquals("пять мкМ, пять М, пять метров", n("5 мкМ, 5 М, 5 м"))
        assertEquals("от латинского homo, с греческого logos", n("от лат. homo, с греч. logos"))
        assertEquals("Святого Георгия, Святой Анны, Святой Пётр, святая Анна, Святому Николаю",
            n("Св. Георгия, Св. Анны, Св. Пётр, св. Анна, Св. Николаю"))
    }

    // Четвёртая порция: диапазон номеров глав, дробь в падеже, «при N %», «1у», «В 300-200 г.».
    @Test fun chapterRangesAndCasedFractions() {
        assertEquals("В главах с первой по третью. В томах со второго по третий опубликованы. Главы с четвёртой по десятую",
            n("В главах 1–3. В томах 2–3 опубликованы. Главы 4-10"))
        assertEquals("без ста сотых, к одной тысяче сотых, равна пяти седьмым, около одной второй, пять седьмых",
            n("без 100/100, к 1000/100, равна 5/7, около 1/2, 5/7"))
        assertEquals("при пяти процентах, при двадцати одном проценте, шёл одну минуту, двадцать одну тысячу",
            n("при 5 %, при 21 %, шёл 1у минуту, 21-у тысячу"))
        assertEquals("В трёхсотом – двухсотом годах, двести-триста граммов муки, весом двести-триста граммов.",
            n("В 300-200 г., 200-300 г муки, весом 200-300 г."))
    }
}
