package ru.kost.ruvoice.text

import org.junit.Assert.assertEquals
import org.junit.Test

/** Правило «Коды и номера карт»: коды из СМС, пароли, PIN, карты — по цифрам. */
class CodesTest {
    private fun n(s: String, rules: Rules = Rules()) = Normalizer.numbers(s, rules)

    @Test fun codeAfterWord() {
        assertEquals("Ваш код: четыре восемь два, девять один три", n("Ваш код: 482913"))
        assertEquals("Код подтверждения четыре восемь, два девять. Никому не сообщайте", n("Код подтверждения 4829. Никому не сообщайте"))
        assertEquals("Ваш пароль для входа в Госуслуги: пять девять три, ноль два, один семь", n("Ваш пароль для входа в Госуслуги: 5930217"))
        assertEquals("код: один два три, четыре пять шесть", n("код: 123 456"))
        assertEquals("CVC один два три", n("CVC 123"))
        assertEquals("Код ошибки четыре ноль четыре", n("Код ошибки 404"))
    }

    @Test fun codeBeforeWord() {
        assertEquals("четыре восемь два, девять один три — ваш код для входа", n("482913 — ваш код для входа"))
    }

    @Test fun cards() {
        assertEquals("Карта один два три четыре, пять шесть семь восемь, девять ноль один два, три четыре пять шесть",
            n("Карта 1234 5678 9012 3456"))
        assertEquals("по карте один два три четыре на", n("по карте ••1234 на"))
        assertEquals("Карта один два три четыре", n("Карта *1234"))
    }

    @Test fun notCodes() {
        // слово «код» рядом, но число — год, количество или часть другого слова
        assertEquals("Код две тысячи двадцать четвёртого года", n("Код 2024 года"))
        assertEquals("кодекс одна тысяча двести тридцать четыре", n("кодекс 1234"))
        assertEquals("код региона семьдесят семь", n("код региона 77"))
        assertEquals("кодом три раза", n("кодом 3 раза"))
        assertEquals("итого один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь", n("итого 1234567"))
    }

    @Test fun switchedOff() {
        assertEquals("Ваш код: четыреста восемьдесят две тысячи девятьсот тринадцать", n("Ваш код: 482913", Rules(setOf("codes"))))
    }
}
