package ru.kost.ruvoice.text

import android.content.Context
import android.util.Log

/**
 * Имена служебных символов для правила symbol_names: знак, который модель не знает и фильтр
 * Normalizer.symbols иначе молча выкинул бы, читается словами. Сначала своя таблица [NAMES] —
 * названия как у TalkBack (values-ru, symbol_*), чтобы голос не спорил с самой читалкой; остальное —
 * из Unicode CLDR (assets/symbols_ru.tsv, tools/symbols_ru.py, сотни знаков: математика, стрелки,
 * валюты, типографика). Обычная пунктуация не называется ни там, ни там — это паузы.
 */
object SymbolNames {
    val NAMES: Map<Char, String> = mapOf(
        '→' to "стрелка вправо", '←' to "стрелка влево", '↑' to "стрелка вверх", '↓' to "стрелка вниз",
        '↔' to "стрелка влево-вправо", '⇒' to "двойная стрелка вправо", '⇐' to "двойная стрелка влево",
        '⟶' to "стрелка вправо", '➔' to "стрелка вправо",
        '▲' to "треугольник вверх", '▼' to "треугольник вниз", '▶' to "треугольник вправо", '◀' to "треугольник влево",
        '▴' to "треугольник вверх", '▾' to "треугольник вниз", '▸' to "треугольник вправо", '◂' to "треугольник влево",
        '△' to "белый треугольник вверх", '▽' to "белый треугольник вниз", '▷' to "белый треугольник вправо", '◁' to "белый треугольник влево",
        '⋮' to "три точки вертикально", '⋯' to "три точки", '·' to "точка посередине", '•' to "маркер списка",
        '●' to "чёрный круг", '○' to "белый круг", '■' to "чёрный квадрат", '□' to "белый квадрат", '◆' to "чёрный ромб", '◇' to "белый ромб",
        '×' to "знак умножения", '÷' to "знак деления", '=' to "равно", '≠' to "не равно", '<' to "меньше", '>' to "больше",
        '≤' to "меньше или равно", '≥' to "больше или равно", '√' to "квадратный корень", '∞' to "бесконечность", 'π' to "пи",
        '@' to "собака", '#' to "решётка", '*' to "звёздочка", '/' to "косая черта", '\\' to "обратная косая черта",
        '|' to "вертикальная черта", '_' to "подчёркивание", '~' to "тильда", '^' to "крышка", '`' to "гравис",
        '{' to "открывающая фигурная скобка", '}' to "закрывающая фигурная скобка",
        '[' to "открывающая квадратная скобка", ']' to "закрывающая квадратная скобка",
        '©' to "знак авторского права", '®' to "зарегистрированный товарный знак", '™' to "товарный знак",
        '✓' to "галочка", '✔' to "галочка", '✗' to "крестик", '✘' to "крестик", '✕' to "крестик", '✖' to "крестик",
        '★' to "чёрная звезда", '☆' to "белая звезда", '♥' to "сердце", '♡' to "белое сердце",
        '¶' to "знак абзаца", '§' to "параграф", '°' to "градус", '%' to "процент", '‰' to "промилле", '№' to "номер",
        '$' to "доллар", '€' to "евро", '₽' to "рубль", '£' to "фунт", '¥' to "иена", '¢' to "цент", '₴' to "гривна", '₸' to "тенге",
        'µ' to "микро", '†' to "крестик", '‡' to "двойной крестик", '※' to "знак сноски",
    )

    /** Таблица CLDR; ставит SileroModels.data(), null — только своя таблица (JVM-тесты без ассета). */
    @Volatile var cldr: Map<Char, String>? = null

    /** Имя знака или null: буквы, цифры, пробелы, знаки ударения и неизвестное не называем. */
    fun of(c: Char): String? = NAMES[c] ?: cldr?.get(c)

    fun parse(lines: Sequence<String>): Map<Char, String> = lines
        .filter { !it.startsWith("#") && it.length > 2 && it[1] == '\t' }
        .associate { it[0] to it.substring(2) }

    fun open(context: Context): Map<Char, String> {
        val t = System.nanoTime()
        return context.assets.open("symbols_ru.tsv").bufferedReader().useLines { parse(it) }
            .also { Log.i("RuVoice", "symbols_ru.tsv: ${it.size} знаков, ${(System.nanoTime() - t) / 1_000_000} мс") }
    }
}
