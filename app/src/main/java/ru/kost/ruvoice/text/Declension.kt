        arrayOf("тринадцать", "тринадцати", "тринадцати", "тринадцать", "тринадцатью", "тринадцати"),
        arrayOf("четырнадцать", "четырнадцати", "четырнадцати", "четырнадцать", "четырнадцатью", "четырнадцати"),
        arrayOf("пятнадцать", "пятнадцати", "пятнадцати", "пятнадцать", "пятнадцатью", "пятнадцати"),
        arrayOf("шестнадцать", "шестнадцати", "шестнадцати", "шестнадцать", "шестнадцатью", "шестнадцати"),
        arrayOf("семнадцать", "семнадцати", "семнадцати", "семнадцать", "семнадцатью", "семнадцати"),
        arrayOf("восемнадцать", "восемнадцати", "восемнадцати", "восемнадцать", "восемнадцатью", "восемнадцати"),
        arrayOf("девятнадцать", "девятнадцати", "девятнадцати", "девятнадцать", "девятнадцатью", "девятнадцати"),
    )
    // Женский род — только у 1 и 2, у остальных числительных рода нет.
    private val oneF = arrayOf("одна", "одной", "одной", "одну", "одной", "одной")
    private val twoF = arrayOf("две", "двух", "двум", "две", "двумя", "двух")

    // Десятки, индекс = десяток (2..9), индексы 0,1 не используются.
    private val tens = arrayOf(
        emptyArray(), emptyArray(),
        arrayOf("двадцать", "двадцати", "двадцати", "двадцать", "двадцатью", "двадцати"),
        arrayOf("тридцать", "тридцати", "тридцати", "тридцать", "тридцатью", "тридцати"),
        arrayOf("сорок", "сорока", "сорока", "сорок", "сорока", "сорока"),
        arrayOf("пятьдесят", "пятидесяти", "пятидесяти", "пятьдесят", "пятьюдесятью", "пятидесяти"),
        arrayOf("шестьдесят", "шестидесяти", "шестидесяти", "шестьдесят", "шестьюдесятью", "шестидесяти"),
        arrayOf("семьдесят", "семидесяти", "семидесяти", "семьдесят", "семьюдесятью", "семидесяти"),
        arrayOf("восемьдесят", "восьмидесяти", "восьмидесяти", "восемьдесят", "восьмьюдесятью", "восьмидесяти"),
        arrayOf("девяносто", "девяноста", "девяноста", "девяносто", "девяноста", "девяноста"),
    )

    // Сотни, индекс = сотня (1..9), индекс 0 не используется.
    private val hundreds = arrayOf(
        emptyArray(),
        arrayOf("сто", "ста", "ста", "сто", "ста", "ста"),
        arrayOf("двести", "двухсот", "двумстам", "двести", "двумястами", "двухстах"),
        arrayOf("триста", "трёхсот", "трёмстам", "триста", "тремястами", "трёхстах"),
        arrayOf("четыреста", "четырёхсот", "четырёмстам", "четыреста", "четырьмястами", "четырёхстах"),
        arrayOf("пятьсот", "пятисот", "пятистам", "пятьсот", "пятьюстами", "пятистах"),
        arrayOf("шестьсот", "шестисот", "шестистам", "шестьсот", "шестьюстами", "шестистах"),
        arrayOf("семьсот", "семисот", "семистам", "семьсот", "семьюстами", "семистах"),
        arrayOf("восемьсот", "восьмисот", "восьмистам", "восемьсот", "восьмьюстами", "восьмистах"),
        arrayOf("девятьсот", "девятисот", "девятистам", "девятьсот", "девятьюстами", "девятистах"),
    )

    // Существительное-разряд: формы для количества 1 / 2-4 / 5+ (и 11-14, 0).
    private val thousandForms = arrayOf(
        arrayOf("тысяча", "тысячи", "тысяче", "тысячу", "тысячей", "тысяче"),
        arrayOf("тысячи", "тысяч", "тысячам", "тысячи", "тысячами", "тысячах"),
        arrayOf("тысяч", "тысяч", "тысячам", "тысяч", "тысячами", "тысячах"),
    )
    private val millionForms = arrayOf(
        arrayOf("миллион", "миллиона", "миллиону", "миллион", "миллионом", "миллионе"),
        arrayOf("миллиона", "миллионов", "миллионам", "миллиона", "миллионами", "миллионах"),
        arrayOf("миллионов", "миллионов", "миллионам", "миллионов", "миллионами", "миллионах"),
    )
    private val billionForms = arrayOf(
        arrayOf("миллиард", "миллиарда", "миллиарду", "миллиард", "миллиардом", "миллиарде"),
        arrayOf("миллиарда", "миллиардов", "миллиардам", "миллиарда", "миллиардами", "миллиардах"),
        arrayOf("миллиардов", "миллиардов", "миллиардам", "миллиардов", "миллиардами", "миллиардах"),
    )

    /** 0 → форма «1», 1 → «2-4», 2 → «5+, 11-14» — как согласование числительного с существительным. */
    private fun bucket(n: Long): Int {
        val r100 = n % 100
        val r10 = n % 10
        return when {
            r100 in 11..19 -> 2
            r10 == 1L -> 0
            r10 in 2..4 -> 1
            else -> 2
        }
    }

    private fun digitForms(d: Int, case: Case, feminine: Boolean): String = when {
        feminine && d == 1 -> oneF[case.ordinal]
        feminine && d == 2 -> twoF[case.ordinal]
        else -> digits[d][case.ordinal]
    }

    /** Число 0..999 целиком в падеже, все слова склоняются (сотни, десятки, единицы). */
    private fun below1000(n: Int, case: Case, feminine: Boolean): String {
        if (n == 0) return ""
        val parts = mutableListOf<String>()
        if (n / 100 > 0) parts += hundreds[n / 100][case.ordinal]
        val rest = n % 100
        if (rest in 1..19) parts += digitForms(rest, case, feminine)
        else if (rest >= 20) {
            parts += tens[rest / 10][case.ordinal]
            val u = rest % 10
            if (u > 0) parts += digitForms(u, case, feminine)
        }
        return parts.joinToString(" ")
    }

    // ponytail: остаток 0..999 после тысяч/миллионов/миллиардов — сотня в именительной форме,
    // склоняются только десятки-единицы (пример из брифа: «1917» в PRE → «...девятьсот семнадцати»,
    // а не «...девятистах семнадцати»). Для NOM/ACC разницы нет (сотни: ACC = NOM), расхождение
    // только в GEN/DAT/INS/PRE у чисел вида сотня+хвост, идущих следом за разрядом. Подтверждено
    // только тестом на 1917 — если встретится другая комбинация с иным поведением, проверить отдельно.
    private fun remainderBelow1000(n: Int, case: Case, feminine: Boolean): String {
        val h = n / 100
        val rest = n % 100
        if (h == 0 || rest == 0) return below1000(n, case, feminine)
        val parts = mutableListOf(hundreds[h][Case.NOM.ordinal])
        if (rest in 1..19) parts += digitForms(rest, case, feminine)
        else {
            parts += tens[rest / 10][case.ordinal]
            val u = rest % 10
            if (u > 0) parts += digitForms(u, case, feminine)
        }
        return parts.joinToString(" ")
    }

    private fun scaleWord(forms: Array<Array<String>>, count: Long, case: Case) = forms[bucket(count)][case.ordinal]

    /** Количественное числительное в падеже. feminine — для 1 и 2 (одна/две, одной/двух…). n в 0..999_999_999_999. */
    fun cardinal(n: Long, case: Case, feminine: Boolean = false): String {
        if (n == 0L) return digits[0][case.ordinal]
        val parts = mutableListOf<String>()
        var rest = n
        val billions = rest / 1_000_000_000L
        rest %= 1_000_000_000L
        if (billions > 0) {
            parts += below1000(billions.toInt(), case, false)
            parts += scaleWord(billionForms, billions, case)
        }
        val millions = rest / 1_000_000L
        rest %= 1_000_000L
        if (millions > 0) {
            parts += below1000(millions.toInt(), case, false)
            parts += scaleWord(millionForms, millions, case)
        }
        val thousands = rest / 1000L
        rest %= 1000L
        if (thousands > 0) {
            // тысяча — существительное женского рода, само числительное перед ней тоже женского рода
            parts += below1000(thousands.toInt(), case, true)
            parts += scaleWord(thousandForms, thousands, case)
        }
        if (rest > 0) {
            parts += if (parts.isEmpty()) below1000(rest.toInt(), case, feminine)
            else remainderBelow1000(rest.toInt(), case, feminine)
        }
        return parts.joinToString(" ")
    }
}
