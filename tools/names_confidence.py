#!/usr/bin/env python3
"""Уверенность акцентора на именах: softmax-вероятность выбранной гласной против нормы. Итог: 23 ошибки из 69, почти все с 1,0 —
порог уверенности для имён бесполезен, список «неуверенных» на вкладке «Проверка» убран. Запуск: python3 tools/names_confidence.py"""
import os, torch
from torch.jit.mobile import _load_for_lite_interpreter
acc = _load_for_lite_interpreter(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app/src/main/assets/silero/accentor.ptl"))
V = 'аоуыэиеяёю'
def pred(w):
    s, y = acc([w]); p = torch.softmax(s[0].detach(), 0)
    vow = [i for i, c in enumerate(w) if c in V]
    k = int(p.argmax()); pr = float(p.max())
    if k < len(vow): w = w[:vow[k]] + '+' + w[vow[k]:]
    return w, pr
# имя, как должно (по норме/книге)
truth = '''перро=перр+о абдул=абд+ул аттила=атт+ила отис=+отис свенсон=св+енсон гельмгольца=гельмг+ольца гомановская=гом+ановская
шенноновская=ш+енноновская лесси=л+есси фарук=фар+ук драконоборца=драконоб+орца амалиты=амал+иты верховины=верхов+ины сейко=с+ейко
хагрид=х+агрид гермиона=герми+она дамблдор=д+амблдор снегг=сн+егг долгопупс=долгоп+упс уизли=у+изли малфой=м+алфой
бэггинс=б+эггинс гэндальф=г+эндальф арагорн=ар+агорн леголас=л+еголас боромир=бор+омир саруман=с+аруман фродо=фр+одо
кингсбридж=к+ингсбридж облонский=обл+онский бальмонт=бальм+онт заболоцкий=забол+оцкий вронский=вр+онский левин=л+евин каренина=кар+енина
ставрогин=ставр+огин раскольников=раск+ольников свидригайлов=свидриг+айлов мармеладов=мармел+адов разумихин=разум+ихин
геральт=гер+альт цири=ц+ири йеннифэр=йенниф+эр трисс=тр+исс лютик=л+ютик кагыр=каг+ыр эмгыр=+эмгыр
корвин=к+орвин амбер=+амбер дворкин=дв+оркин бенедикт=бенед+икт джулиан=дж+улиан
ведьмак=ведьм+ак тирион=т+ирион дейенерис=дейен+ерис ланнистер=л+аннистер старк=ст+арк таргариен=тарг+ариен
курылёв=курыл+ёв дивов=д+ивов лукьяненко=лукь+яненко пехов=п+ехов громыко=гром+ыко стругацкие=струг+ацкие
мураками=мурак+ами кавабата=каваб+ата акутагава=акутаг+ава хокусай=хокус+ай
нкоми=нк+оми'''.split()
rows = []
for t in truth:
    w, want = t.split('='); got, pr = pred(w); rows.append((pr, got == want, got, want))
rows.sort()
for pr, ok, got, want in rows: print(f'{pr:.2f} {"ok " if ok else "БАГ"} {got:16} {"" if ok else want}')
n = len(rows); bad = sum(not r[1] for r in rows)
print(f'всего {n}, ошибок {bad}')
for th in (0.5, 0.6, 0.7, 0.8, 0.9, 0.95):
    low = [r for r in rows if r[0] < th]; print(f'порог {th}: ниже {len(low)}, из них ошибок {sum(not r[1] for r in low)}; выше ошибок {sum(not r[1] for r in rows if r[0] >= th)}')
